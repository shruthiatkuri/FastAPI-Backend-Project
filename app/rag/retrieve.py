import os
import numpy as np
import psycopg
import openai
from dotenv import load_dotenv
from openai import OpenAI
from pgvector.psycopg import register_vector
import hashlib

load_dotenv(override=True)
oai=OpenAI()
response_cache: dict[str, str]={}

SYSTEM = (
    "You answer questions using ONLY the provided context. "
    "If the answer is not in the context, say you don't know. "
    "Cite the source of each fact."
)

conn= psycopg.connect(os.environ["DATABASE_URL"])
register_vector(conn)

def retrieve(question:str,k:int =4):
    """
    Retrieve the most relevant document chunks from the PostgreSQL vector
    database using semantic similarity search.

    Generates an embedding for the user's question using OpenAI's
    text-embedding-3-small model. Executes a similarity search against the
    stored document embeddings using PostgreSQL's cosine distance operator
    and retrieves the top-k most relevant document chunks.

    Args:
        question (str): User's question to convert into an embedding and
            use as the search query.
        k (int, optional): Maximum number of relevant document chunks
            to retrieve. Defaults to 4.

    Returns:
        list[dict]: A list of dictionaries containing:
            - document (str): Retrieved document chunk.
            - cmetadata (dict): Metadata associated with the document,
              such as its source file.
            - distance (float): Cosine distance between the question
              embedding and the stored document embedding. Lower values
              indicate greater similarity.
    """

    qv= np.array(oai.embeddings.create(model="text-embedding-3-small",
                                       input=question).data[0].embedding)
    rows=conn.execute(
        """
        SELECT document,cmetadata, (embedding::vector(1536)) <=> %s AS distance
        FROM langchain_pg_embedding
        ORDER BY (embedding::vector(1536)) <=> %s
        LIMIT %s
        """,
        (qv, qv, k),
    ).fetchall()
    return [{"document":doc,"cmetadata":c, "distance":d} for doc,c,d in rows]


def answer(question:str):
    """
    Generate an answer to the user's question using retrieved document
    context and the OpenAI GPT-4o model.

    Calls retrieve() to fetch the most relevant document chunks from the
    vector database. Combines the retrieved chunks and their metadata into
    a context string, then passes the context and user's question to GPT-4o
    for answer generation.

    The response is generated in streaming mode, yielding each non-empty
    text chunk as it becomes available instead of waiting for the complete
    response.

    Args:
        question (str): User's question to retrieve relevant documents
            and generate an answer.

    Yields:
        str: Individual text chunks generated by the language model.
             The chunks can be combined to form the complete answer.
    """
    
    chunks=retrieve(question)
    #print("RETRIEVED CHUNKS:", len(chunks))
    context="\n\n".join(f"[{c['cmetadata']}] {c['document']}" for c in chunks)
     
    
    #print("CONTEXT:", context[:500])

    response= oai.chat.completions.create(
        model="gpt-4o",
        max_tokens=1024,
        messages=[{"role":"system", "content":SYSTEM},
                  {"role":"user","content":f"Context:\n{context}\n\nQuestion:{question}"}],
                  stream=True

    )
    for chunk in response:
        piece=chunk.choices[0].delta.content
        if piece:
            yield piece

def cached_answer(question: str):
    """
    Generate and stream an answer using a simple in-memory response cache.

    Generates a SHA-256 hash of the user's question to use as a cache key.
    Checks whether the question already exists in the response cache.

    If a cached response exists (cache hit), yields the stored answer
    immediately without calling the answer-generation function.

    If no cached response exists (cache miss), calls answer() to generate
    a streaming response. Collects the generated text chunks while yielding
    them to the caller. Once generation is complete, combines the chunks
    into a complete response and stores it in the cache for future requests.

    Handles OpenAI rate-limit and API timeout errors by yielding appropriate
    error messages instead of allowing these exceptions to interrupt
    the response stream.

    Args:
        question (str): User's question used to generate or retrieve
            a cached response.

    Yields:
        str: Individual text chunks from the generated response, the
            complete cached response on a cache hit, or an error message
            if a rate-limit or timeout exception occurs.
    """


    print("CACHED FUNCTION CALLED", flush=True)

    key = hashlib.sha256(question.encode()).hexdigest()

    if key in response_cache:
        #print("CACHE HIT", flush=True)
        yield response_cache[key]
        return

    #print("CACHE MISS", flush=True)

    pieces = []

    try:

        for piece in answer(question):
            pieces.append(piece)
            yield piece

        response_cache[key] = "".join(pieces)
    except openai.RateLimitError:
        print("Rate limited - try again later", flush=True)
        yield "\nRate limit exceeded. Please try again later."

    except openai.APITimeoutError:
        print("Timeout", flush=True)
        yield "\nRequest timed out. Please try again."