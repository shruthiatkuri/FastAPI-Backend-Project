
import openai
import hashlib
import json

from app.rag.agent import agent
from langchain_core.messages import ToolMessage

response_cache = {}

def cached_answer(question: str):
    """
    Generate and stream an AI agent response with in-memory caching and
    source attribution using Server-Sent Events (SSE).

    Generates a SHA-256 hash of the user's question to use as a cache key.
    Checks whether a previously generated answer and its source documents
    are available in the response cache.

    If a cached response exists (cache hit), retrieves the stored answer
    and sources and streams them as SSE events without invoking the agent.

    If no cached response exists (cache miss), invokes the LangGraph agent
    in message streaming mode. Collects text chunks generated by the model
    and streams them as token events. Also identifies tool messages
    containing source documents in their artifacts and collects unique
    sources.

    After the agent finishes generating its response, combines the text
    chunks into a complete answer and stores the answer and associated
    sources in the response cache.

    Streams the collected sources as a source event and signals completion
    using a done event.

    Handles OpenAI rate-limit errors, API timeout errors, and unexpected
    exceptions by streaming appropriate error events.

    Args:
        question (str): User's question used to generate or retrieve
            a cached agent response.

    Yields:
        str: Server-Sent Events (SSE) formatted strings representing:
            - token: Individual text chunks generated by the agent,
            or the complete cached answer.
            - source: Retrieved source documents associated with the answer.
            - done: Signals that response streaming has completed.
            - error: Describes a rate-limit, timeout, or unexpected error.

    The response cache is stored in application memory and is not
    persistent across application restarts.
    """
    key = hashlib.sha256(question.encode()).hexdigest()

    if key in response_cache:
        
        answer= response_cache[key]["answer"]
        source= response_cache[key]["source"]
        print("CACHE STORED:", response_cache[key], flush=True)

        for piece in [answer]:
            yield f"data:{json.dumps({'type':'token','content':piece})}\n\n"

       
        yield f"data:{json.dumps({'type':'source','content':source})}\n\n"
        yield f"data:{json.dumps({'type':'done'})}\n\n"
        return


    pieces = []
    source = []

    try:
        for message_chunk, metadata in agent.stream(
        {
            "messages": [
                {
                    "role": "user",
                    "content": question
                }
            ]
        },
        stream_mode="messages"
    ):
            
            node = metadata.get("langgraph_node")

            if node == "model":
                if isinstance(message_chunk.content, str) and message_chunk.content:
                    pieces.append(message_chunk.content)
                    yield f"data:{json.dumps({'type':'token','content':message_chunk.content})}\n\n"

            if isinstance(message_chunk, ToolMessage) and message_chunk.artifact:
                for s in message_chunk.artifact:
                    if s not in source:
                        source.append(s)

        answer= "".join(pieces)

        response_cache[key] ={
            "answer":answer,
            "source":source
        }

        yield f"data: {json.dumps({'type':'source', 'content':source})}\n\n"
        yield f"data: {json.dumps({'type':'done'})}\n\n"

    except openai.RateLimitError:
        print("Rate limit exceeded", flush=True)
        yield f"data: {json.dumps({'type': 'error', 'content': 'Rate limit exceeded. Please try again later.'})}\n\n"
    except openai.APITimeoutError:
        print("Request timed out", flush=True)
        yield f"data:{json.dumps({'type':'error', 'content':'Request timed out. Please try again.'})}\n\n"

    except Exception as e:
        print(f"Unexpected error: {e}", flush=True)
        yield f"data:{json.dumps({'type':'error', 'content':'An unexcepted error occured,'})}\n\n"


