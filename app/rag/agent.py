from langchain.agents import create_agent
from langchain_openai import ChatOpenAI
from langchain_core.messages import ToolMessage

from app.rag.product_price_tool import get_product_price
from app.rag.tools import search_documents

tools = [
    get_product_price,
    search_documents
]

llm = ChatOpenAI(
    model="gpt-4o",
    temperature=0
)

agent = create_agent(
    model=llm,
    tools=tools,
    system_prompt=(

        "You are a helpful e-commerce and knowledge assistant. "

        "Use get_product_price when the user asks about a product's price. "

        "Use search_documents when the user asks questions about the knowledge base. "

        "For knowledge-base questions, answer ONLY using information "
        "returned by search_documents. "

        "Never use your own general knowledge to answer knowledge-base questions. "

        "If search_documents cannot find the requested information, "
        "respond with: I don't know. "

        "Do not invent product prices or document-based facts. ")
)

def get_agent_response(question: str):
    """
    Invoke the AI agent to generate an answer and collect the source
    documents retrieved by its tools.

    Sends the user's question to the agent through its message interface.
    The agent processes the question, determines which tools to use,
    and generates a final response.

    Extracts the final answer from the last message in the agent's
    message history. Iterates through the message history to identify
    ToolMessage objects containing source documents in their artifacts.
    Collects unique sources to avoid duplicate entries.

    Args:
        question (str): User's question to be processed by the AI agent.

    Returns:
        dict: A dictionary containing:
            - answer (str): The final response generated by the agent.
            - sources (list): A list of unique source documents returned
              by the agent's retrieval tools.
    """

    result = agent.invoke({
        "messages": [
            {"role": "user", "content": question}
        ]
    })

    answer = result["messages"][-1].content

    sources = []

    for message in result["messages"]:
        if isinstance(message, ToolMessage) and message.artifact:
            for source in message.artifact:
                if source not in sources:
                    sources.append(source)

    return {
        "answer": answer,
        "sources": sources
    }